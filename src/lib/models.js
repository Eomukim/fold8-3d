/* ---------- cover-panel rectangle from a diagonal + pixel aspect ---------- */

function coverRect(diagIn, res) {
  const d = diagIn * 2.54;
  const [long, short] = res[0] >= res[1] ? res : [res[1], res[0]];
  const w = (d * short) / Math.hypot(long, short);
  const h = (d * long) / Math.hypot(long, short);
  return { w, h };
}

