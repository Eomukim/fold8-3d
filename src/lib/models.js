/* ---------- assemble ---------- */

function prep(m, series) {
  const r = coverRect(m.cover.diag, m.cover.res);
  const isBook = series === 'fold';
  const half = isBook ? m.dims.w / 2 : m.dims.h / 2;
  const across = isBook ? m.dims.h : m.dims.w;

  const colors = COLORWAYS[m.id].map((c, i) => ({ ...c, idx: i }));

  return {
    ...m,
    series,
    form: isBook ? 'book' : 'flip',
    half,
    across,
    coverW: r.w,
    coverH: r.h,
    colors,
    hinge: HINGE[m.id],
    seam: isBook ? 0.06 : 0.06,
    flex: isBook ? 115 : 95,
    colorway: colors[0].id,
  };
}

export const CATALOG = {
  fold: FOLD.map((m) => prep(m, 'fold')),
  flip: FLIP.map((m) => prep(m, 'flip')),
};

export const SERIES_META = {
  fold: { id: 'fold', label: 'FOLD', ko: '북 스타일', axis: '세로 접힘' },
  flip: { id: 'flip', label: 'FLIP', ko: '클램셸', axis: '가로 접힘' },
};

export function findModel(series, id) {
  const list = CATALOG[series] ?? CATALOG.fold;
  return list.find((m) => m.id === id) ?? list[0];
}

